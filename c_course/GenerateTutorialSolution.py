r"""
GenerateTutorialSolution.py

Purpose:
    Create KarasCTutorial.sln in the C tutorial examples folder, with one
    Visual Studio 2026 C project (<name>\<name>.vcxproj) per example program,
    replacing the old Visual C++ 6 workspace (.dsw) and projects (.dsp).

    Each project compiles ..\<name>.c as C (not C++), for Win32 and x64,
    Debug and Release. Executables go to examples\bin\<platform>\<config>\,
    intermediate files to examples\obj\<name>\..., so the source folder stays
    clean. Debugger settings live in the project itself, so F5 or Ctrl+F5 on
    the startup project just runs it: args gets sample command line
    arguments and symbols gets a MYSYM environment variable to find.

    key.c needs VMS RMS headers, so its project is in the solution for
    reading but is not ticked for building in any solution configuration.

    Project GUIDs are derived from the project names, so running this again
    produces identical files rather than new GUIDs.

Usage:
    python -I GenerateTutorialSolution.py <examples folder>

Example (cmd, run from this c_course folder):
    python -I GenerateTutorialSolution.py examples

Adding a new example:
    1. Put <name>.c (and any other files it needs) in the examples folder,
       in Windows-1252 with CRLF line endings like the others.
    2. Add <name> to the end of EXAMPLES below. If it is built from more
       than one file, also list its files in SOURCE_FILES and HEADER_FILES.
    3. Run this script. Existing projects come out byte-for-byte the same,
       because each project's GUID is derived from its name.
    4. If the example is listed on the course page, copy the listing in from
       the file (from its "/*----" title line on) so the two stay identical.
"""

import os
import sys
import uuid

# hello first: the first project in a solution is the default startup project.
EXAMPLES = ['hello', 'scope', 'loops', 'treesort', 'charsign', 'input', 'fileio',
            'calc', 'args', 'key', 'symbols', 'time', 'signal', 'vargs',
            'functable', 'strings', 'dcl', 'self', 'xmas', 'stackdemo', 'sort']
NOT_BUILT_ON_WINDOWS = {'key'}

# Projects built from more than one file; every other project compiles
# just <name>.c. Headers are listed so they show in Solution Explorer.
SOURCE_FILES = {'stackdemo': ['stackdemo.c', 'stack.c']}
HEADER_FILES = {'stackdemo': ['stack.h']}

# Extra debugger settings for examples that need input from outside to show
# what they do.
DEBUGGER_SETTINGS = {
    'args': '    <LocalDebuggerCommandArguments>hello world "and a quoted argument"</LocalDebuggerCommandArguments>\n',
    'symbols': '    <LocalDebuggerEnvironment>MYSYM=Hello from Visual Studio</LocalDebuggerEnvironment>\n',
}

CPP_PROJECT_TYPE = '{8BC9CEB8-8B4A-11D0-8D11-00A0C91BC942}'
NAMESPACE = uuid.UUID('6f1c2a4e-3b5d-4e7f-9a1b-2c3d4e5f6a7b')   # fixed, for stable GUIDs


def project_guid(name):
    return '{%s}' % str(uuid.uuid5(NAMESPACE, 'KarasCTutorial/' + name)).upper()


SOLUTION_GUID = '{%s}' % str(uuid.uuid5(NAMESPACE, 'KarasCTutorial.sln')).upper()

PROJECT_TEMPLATE = '''<?xml version="1.0" encoding="utf-8"?>
<!--
  Kara's C Course example "{name}.c", compiled as C with Visual Studio 2026
  (platform toolset v145). Generated by GenerateTutorialSolution.py.{key_note}
-->
<Project DefaultTargets="Build" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">
  <ItemGroup Label="ProjectConfigurations">
    <ProjectConfiguration Include="Debug|Win32">
      <Configuration>Debug</Configuration>
      <Platform>Win32</Platform>
    </ProjectConfiguration>
    <ProjectConfiguration Include="Release|Win32">
      <Configuration>Release</Configuration>
      <Platform>Win32</Platform>
    </ProjectConfiguration>
    <ProjectConfiguration Include="Debug|x64">
      <Configuration>Debug</Configuration>
      <Platform>x64</Platform>
    </ProjectConfiguration>
    <ProjectConfiguration Include="Release|x64">
      <Configuration>Release</Configuration>
      <Platform>x64</Platform>
    </ProjectConfiguration>
  </ItemGroup>
  <PropertyGroup Label="Globals">
    <VCProjectVersion>18.0</VCProjectVersion>
    <Keyword>Win32Proj</Keyword>
    <ProjectGuid>{guid}</ProjectGuid>
    <RootNamespace>{name}</RootNamespace>
    <WindowsTargetPlatformVersion>10.0</WindowsTargetPlatformVersion>
  </PropertyGroup>
  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.Default.props" />
  <PropertyGroup Label="Configuration">
    <ConfigurationType>Application</ConfigurationType>
    <PlatformToolset>v145</PlatformToolset>
    <CharacterSet>MultiByte</CharacterSet>
  </PropertyGroup>
  <PropertyGroup Condition="'$(Configuration)'=='Debug'" Label="Configuration">
    <UseDebugLibraries>true</UseDebugLibraries>
  </PropertyGroup>
  <PropertyGroup Condition="'$(Configuration)'=='Release'" Label="Configuration">
    <UseDebugLibraries>false</UseDebugLibraries>
    <WholeProgramOptimization>true</WholeProgramOptimization>
  </PropertyGroup>
  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.props" />
  <ImportGroup Label="PropertySheets">
    <Import Project="$(UserRootDir)\\Microsoft.Cpp.$(Platform).user.props" Condition="exists('$(UserRootDir)\\Microsoft.Cpp.$(Platform).user.props')" Label="LocalAppDataPlatform" />
  </ImportGroup>
  <PropertyGroup>
    <!-- All the example programs in one bin folder; intermediate files kept apart per project -->
    <OutDir>$(MSBuildThisFileDirectory)..\\bin\\$(Platform)\\$(Configuration)\\</OutDir>
    <IntDir>$(MSBuildThisFileDirectory)..\\obj\\$(ProjectName)\\$(Platform)\\$(Configuration)\\</IntDir>
    <!-- Run from this project folder, so files the program writes land here -->
    <LocalDebuggerWorkingDirectory>$(ProjectDir)</LocalDebuggerWorkingDirectory>
    <DebuggerFlavor>WindowsLocalDebugger</DebuggerFlavor>
{debugger_settings}  </PropertyGroup>
  <ItemDefinitionGroup>
    <ClCompile>
      <!-- The examples are ANSI C, so compile them as C, not C++ -->
      <CompileAs>CompileAsC</CompileAs>
      <WarningLevel>Level3</WarningLevel>
      <!-- scanf, strcpy and friends are the subject of the course, so no "unsafe function" errors -->
      <SDLCheck>false</SDLCheck>
      <PreprocessorDefinitions>_CRT_SECURE_NO_WARNINGS;_CONSOLE;%(PreprocessorDefinitions)</PreprocessorDefinitions>
    </ClCompile>
    <Link>
      <SubSystem>Console</SubSystem>
      <GenerateDebugInformation>true</GenerateDebugInformation>
    </Link>
  </ItemDefinitionGroup>
  <ItemDefinitionGroup Condition="'$(Configuration)'=='Debug'">
    <ClCompile>
      <Optimization>Disabled</Optimization>
      <PreprocessorDefinitions>_DEBUG;%(PreprocessorDefinitions)</PreprocessorDefinitions>
    </ClCompile>
  </ItemDefinitionGroup>
  <ItemDefinitionGroup Condition="'$(Configuration)'=='Release'">
    <ClCompile>
      <Optimization>MaxSpeed</Optimization>
      <FunctionLevelLinking>true</FunctionLevelLinking>
      <IntrinsicFunctions>true</IntrinsicFunctions>
      <PreprocessorDefinitions>NDEBUG;%(PreprocessorDefinitions)</PreprocessorDefinitions>
    </ClCompile>
    <Link>
      <EnableCOMDATFolding>true</EnableCOMDATFolding>
      <OptimizeReferences>true</OptimizeReferences>
    </Link>
  </ItemDefinitionGroup>
  <ItemGroup>
{file_items}  </ItemGroup>
  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.targets" />
</Project>
'''

KEY_NOTE = ('\n  key.c uses VMS RMS (rab.h, rms.h, starlet.h), so this project is not\n'
            '  built in any solution configuration; it is here for reading.')


def write_crlf_with_bom(path, text):
    with open(path, 'w', encoding='utf-8-sig', newline='\r\n') as output_file:
        output_file.write(text)


def main():
    examples_folder = sys.argv[1]
    for name in EXAMPLES:
        for file_name in SOURCE_FILES.get(name, [name + '.c']) + HEADER_FILES.get(name, []):
            if not os.path.exists(os.path.join(examples_folder, file_name)):
                sys.exit('refusing: %s is missing' % file_name)

    for name in EXAMPLES:
        project_folder = os.path.join(examples_folder, name)
        os.makedirs(project_folder, exist_ok=True)
        file_items = ''.join('    <ClCompile Include="..\\%s" />\n' % file_name
                             for file_name in SOURCE_FILES.get(name, [name + '.c']))
        file_items += ''.join('    <ClInclude Include="..\\%s" />\n' % file_name
                              for file_name in HEADER_FILES.get(name, []))
        text = PROJECT_TEMPLATE.format(
            name=name, guid=project_guid(name),
            key_note=KEY_NOTE if name in NOT_BUILT_ON_WINDOWS else '',
            debugger_settings=DEBUGGER_SETTINGS.get(name, ''),
            file_items=file_items)
        write_crlf_with_bom(os.path.join(project_folder, name + '.vcxproj'), text)

    solution_platforms = [('Debug', 'x64', 'x64'), ('Debug', 'x86', 'Win32'),
                          ('Release', 'x64', 'x64'), ('Release', 'x86', 'Win32')]
    lines = ['',
             'Microsoft Visual Studio Solution File, Format Version 12.00',
             '# Visual Studio Version 18',
             'VisualStudioVersion = 18.0.11205.157',
             'MinimumVisualStudioVersion = 10.0.40219.1']
    for name in EXAMPLES:
        lines.append('Project("%s") = "%s", "%s\\%s.vcxproj", "%s"'
                     % (CPP_PROJECT_TYPE, name, name, name, project_guid(name)))
        lines.append('EndProject')
    lines.append('Global')
    lines.append('\tGlobalSection(SolutionConfigurationPlatforms) = preSolution')
    for configuration, solution_platform, _ in solution_platforms:
        lines.append('\t\t%s|%s = %s|%s' % (configuration, solution_platform, configuration, solution_platform))
    lines.append('\tEndGlobalSection')
    lines.append('\tGlobalSection(ProjectConfigurationPlatforms) = postSolution')
    for name in EXAMPLES:
        for configuration, solution_platform, project_platform in solution_platforms:
            prefix = '\t\t%s.%s|%s' % (project_guid(name), configuration, solution_platform)
            lines.append('%s.ActiveCfg = %s|%s' % (prefix, configuration, project_platform))
            if name not in NOT_BUILT_ON_WINDOWS:
                lines.append('%s.Build.0 = %s|%s' % (prefix, configuration, project_platform))
    lines.append('\tEndGlobalSection')
    lines.append('\tGlobalSection(SolutionProperties) = preSolution')
    lines.append('\t\tHideSolutionNode = FALSE')
    lines.append('\tEndGlobalSection')
    lines.append('\tGlobalSection(ExtensibilityGlobals) = postSolution')
    lines.append('\t\tSolutionGuid = %s' % SOLUTION_GUID)
    lines.append('\tEndGlobalSection')
    lines.append('EndGlobal')
    write_crlf_with_bom(os.path.join(examples_folder, 'KarasCTutorial.sln'), '\n'.join(lines) + '\n')
    print('wrote KarasCTutorial.sln and %d projects' % len(EXAMPLES))


if __name__ == '__main__':
    main()
